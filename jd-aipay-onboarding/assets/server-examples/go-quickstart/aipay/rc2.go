func rc2KeySchedule(key []byte, effectiveBits int) [64]uint16 {
	t := len(key)
	t1 := effectiveBits
	t8 := (t1 + 7) / 8
	tm := byte(0xff) >> byte(8*t8-t1)
	var l [128]byte
	copy(l[:], key)
	for i := t; i < 128; i++ {
		l[i] = rc2PiTable[(int(l[i-1])+int(l[i-t]))&0xff]
	}
	l[128-t8] = rc2PiTable[(int(l[128-t8]&tm))&0xff]
	for i := 127 - t8; i >= 0; i-- {
		l[i] = rc2PiTable[(int(l[i+1])^int(l[i+t8]))&0xff]
	}
	var k [64]uint16
	for i := 0; i < 64; i++ {
		k[i] = uint16(l[2*i]) | uint16(l[2*i+1])<<8
	}
	return k
}

func rc2DecryptBlock(k [64]uint16, block []byte) []byte {
	var r [4]uint16
	for i := 0; i < 4; i++ {
		r[i] = uint16(block[2*i]) | uint16(block[2*i+1])<<8
	}
	s := [4]uint16{1, 2, 3, 5}
	ror := func(v, n uint16) uint16 { return v>>n | v<<(16-n) }
	j := 63
	mixInv := func() {
		for i := 3; i >= 0; i-- {
			r[i] = ror(r[i], s[i])
			// a=R[i-1], b=R[i-2], c=R[i-3]（python 下标 (i-1)%4/(i-2)%4/(i-3)%4）
			a, b, c := r[(i+3)%4], r[(i+2)%4], r[(i+1)%4]
			// 加密式：r[i] += K[j] + (R[i-1] & R[i-2]) + ((~R[i-1]) & R[i-3])
			r[i] = r[i] - k[j] - (a & b) - (^a & c)
			j--
		}
	}
	mashInv := func() {
		for i := 3; i >= 0; i-- {
			r[i] = r[i] - k[int(r[(i+3)%4]&63)]
		}
	}
	for round := 0; round < 5; round++ {
		mixInv()
	}
	mashInv()
	for round := 0; round < 6; round++ {
		mixInv()
	}
	mashInv()
	for round := 0; round < 5; round++ {
		mixInv()
	}
	out := make([]byte, 8)
	for i := 0; i < 4; i++ {
		out[2*i] = byte(r[i])
		out[2*i+1] = byte(r[i] >> 8)
	}
	return out
}

// rc2CBCDecrypt40 RC2-CBC（40 位有效密钥）解密并去 PKCS7 填充。
func rc2CBCDecrypt40(key, iv, data []byte) ([]byte, error) {
	k := rc2KeySchedule(key, 40)
	out := make([]byte, len(data))
	prev := iv
	for off := 0; off+8 <= len(data); off += 8 {
		dec := rc2DecryptBlock(k, data[off:off+8])
		for i := 0; i < 8; i++ {
			out[off+i] = dec[i] ^ prev[i]
		}
		prev = data[off : off+8]
	}
	return pkcs7Unpad(out, 8)
}
